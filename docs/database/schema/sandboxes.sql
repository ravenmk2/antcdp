-- 云电脑结构阅读副本；实际安装执行嵌入式数据库基线。
-- 单一连接、环境模板、云电脑、轮次占用和物理执行记录。
-- 不含种子、实际环境配置或数据修正。

CREATE TABLE `sandbox_connection` (
    `id` BIGINT UNSIGNED NOT NULL,
    `endpoint` VARCHAR(2048) CHARACTER SET ascii COLLATE ascii_bin NULL,
    `access_mode` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `connect_timeout_seconds` INT UNSIGNED NOT NULL,
    `operation_timeout_seconds` INT UNSIGNED NOT NULL,
    `secret_ciphertext` MEDIUMBLOB NULL,
    `secret_format_version` BIGINT UNSIGNED NULL,
    `secret_key_version` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    `secret_revision` BIGINT UNSIGNED NOT NULL,
    `config_version` BIGINT UNSIGNED NOT NULL,
    `row_version` BIGINT UNSIGNED NOT NULL,
    `backend_generation` BIGINT UNSIGNED NOT NULL,
    `topology_version` BIGINT UNSIGNED NOT NULL,
    `maintenance_state` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `verified_capabilities` JSON NULL,
    `last_diagnostic` JSON NULL,
    `last_diagnostic_at` DATETIME(3) NULL,
    `updated_by_user_id` BIGINT UNSIGNED NULL,
    `created_at` DATETIME(3) NOT NULL,
    `updated_at` DATETIME(3) NOT NULL,
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `cloud_computer_template` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `agent_id` BIGINT UNSIGNED NULL,
    `environment` JSON NOT NULL,
    `config_schema_version` BIGINT UNSIGNED NOT NULL,
    `config_version` BIGINT UNSIGNED NOT NULL,
    `row_version` BIGINT UNSIGNED NOT NULL,
    `updated_by_user_id` BIGINT UNSIGNED NULL,
    `created_at` DATETIME(3) NOT NULL,
    `updated_at` DATETIME(3) NOT NULL,
    `owner_key` BIGINT UNSIGNED GENERATED ALWAYS AS (COALESCE(agent_id,0)) STORED,
    PRIMARY KEY (id),
    UNIQUE KEY uq_cloud_template_owner (owner_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `cloud_computer` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `owner_user_id` BIGINT UNSIGNED NOT NULL,
    `pool_agent_id` BIGINT UNSIGNED NULL,
    `state` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `backend_generation` BIGINT UNSIGNED NOT NULL,
    `runtime_generation` BIGINT UNSIGNED NOT NULL,
    `storage_generation` BIGINT UNSIGNED NOT NULL,
    `runtime_id` VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NULL,
    `runtime_creation_token` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    `runtime_expires_at` DATETIME(3) NULL,
    `volume_id` CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    `volume_name` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    `volume_state` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `volume_cleanup_state` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `applied_template_version` BIGINT UNSIGNED NULL,
    `effective_environment` JSON NULL,
    `verified_capabilities` JSON NULL,
    `idle_since` DATETIME(3) NOT NULL,
    `last_activity_at` DATETIME(3) NOT NULL,
    `last_observed_at` DATETIME(3) NULL,
    `error_code` VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NULL,
    `fence_version` BIGINT UNSIGNED NOT NULL,
    `row_version` BIGINT UNSIGNED NOT NULL,
    `deleted_at` DATETIME(3) NULL,
    `created_at` DATETIME(3) NOT NULL,
    `updated_at` DATETIME(3) NOT NULL,
    `personal_owner_id` BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN pool_agent_id IS NULL AND deleted_at IS NULL THEN owner_user_id ELSE NULL END) STORED,
    PRIMARY KEY (id),
    UNIQUE KEY uq_cloud_personal_owner (personal_owner_id),
    UNIQUE KEY uq_cloud_volume_id (volume_id),
    UNIQUE KEY uq_cloud_volume_name (volume_name),
    UNIQUE KEY uq_cloud_runtime (backend_generation,runtime_id),
    UNIQUE KEY uq_cloud_creation_token (runtime_creation_token),
    KEY idx_cloud_pool (pool_agent_id,state,idle_since,id),
    KEY idx_cloud_owner (owner_user_id,deleted_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `cloud_computer_lease` (
    `root_run_id` BIGINT UNSIGNED NOT NULL,
    `cloud_computer_id` BIGINT UNSIGNED NOT NULL,
    `mode` VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `state` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `backend_generation` BIGINT UNSIGNED NOT NULL,
    `runtime_generation` BIGINT UNSIGNED NULL,
    `storage_generation` BIGINT UNSIGNED NOT NULL,
    `skill_set_hash` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `executor_epoch` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `fence_version` BIGINT UNSIGNED NOT NULL,
    `acquired_at` DATETIME(3) NOT NULL,
    `lease_expires_at` DATETIME(3) NOT NULL,
    `released_at` DATETIME(3) NULL,
    `release_reason` VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NULL,
    `updated_at` DATETIME(3) NOT NULL,
    `exclusive_computer_id` BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN mode='exclusive' AND released_at IS NULL THEN cloud_computer_id ELSE NULL END) STORED,
    PRIMARY KEY (root_run_id),
    UNIQUE KEY uq_cloud_lease_exclusive (exclusive_computer_id),
    KEY idx_cloud_lease_computer (cloud_computer_id,released_at,root_run_id),
    KEY idx_cloud_lease_reconcile (state,lease_expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `cloud_computer_skill_state` (
    `cloud_computer_id` BIGINT UNSIGNED NOT NULL,
    `agent_id` BIGINT UNSIGNED NOT NULL,
    `backend_generation` BIGINT UNSIGNED NOT NULL,
    `storage_generation` BIGINT UNSIGNED NOT NULL,
    `installed_set_hash` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `installed_manifest` JSON NOT NULL,
    `state` VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `sync_token` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `fence_version` BIGINT UNSIGNED NOT NULL,
    `row_version` BIGINT UNSIGNED NOT NULL,
    `updated_at` DATETIME(3) NOT NULL,
    PRIMARY KEY (cloud_computer_id,agent_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `cloud_computer_execution` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `cloud_computer_id` BIGINT UNSIGNED NOT NULL,
    `backend_generation` BIGINT UNSIGNED NOT NULL,
    `runtime_generation` BIGINT UNSIGNED NOT NULL,
    `root_run_id` BIGINT UNSIGNED NOT NULL,
    `run_id` BIGINT UNSIGNED NOT NULL,
    `tool_call_id` BIGINT UNSIGNED NOT NULL,
    `execution_ordinal` BIGINT UNSIGNED NOT NULL,
    `execution_token` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `remote_execution_id` VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NULL,
    `is_background` BOOLEAN NOT NULL,
    `status` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `command_event_seq` BIGINT UNSIGNED NOT NULL,
    `cwd` VARCHAR(2048) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `execution_spec_hash` BINARY(32) NOT NULL,
    `executor_epoch` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `fence_version` BIGINT UNSIGNED NOT NULL,
    `exit_code` INT NULL,
    `output_cursor` VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NULL,
    `last_observation` JSON NULL,
    `error_code` VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NULL,
    `created_at` DATETIME(3) NOT NULL,
    `started_at` DATETIME(3) NULL,
    `deadline_at` DATETIME(3) NOT NULL,
    `cancel_requested_at` DATETIME(3) NULL,
    `last_observed_at` DATETIME(3) NULL,
    `finished_at` DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_cloud_execution_call (tool_call_id,execution_ordinal),
    UNIQUE KEY uq_cloud_execution_token (execution_token),
    KEY idx_cloud_execution_root (root_run_id,status,id),
    KEY idx_cloud_execution_computer (cloud_computer_id,status,id),
    KEY idx_cloud_execution_due (status,deadline_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `cloud_computer_operation` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `cloud_computer_id` BIGINT UNSIGNED NOT NULL,
    `root_run_id` BIGINT UNSIGNED NULL,
    `kind` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `status` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `operation_token` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `command_receipt_id` BIGINT UNSIGNED NULL,
    `public_operation_id` BIGINT UNSIGNED NULL,
    `backend_generation` BIGINT UNSIGNED NOT NULL,
    `runtime_generation` BIGINT UNSIGNED NOT NULL,
    `storage_generation` BIGINT UNSIGNED NOT NULL,
    `target_environment` JSON NULL,
    `target_template_version` BIGINT UNSIGNED NULL,
    `intent` JSON NOT NULL,
    `observation` JSON NULL,
    `actor_kind` VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `actor_id` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `executor_epoch` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `fence_version` BIGINT UNSIGNED NOT NULL,
    `error_code` VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NULL,
    `created_at` DATETIME(3) NOT NULL,
    `started_at` DATETIME(3) NULL,
    `deadline_at` DATETIME(3) NOT NULL,
    `cancel_requested_at` DATETIME(3) NULL,
    `finished_at` DATETIME(3) NULL,
    `updated_at` DATETIME(3) NOT NULL,
    `active_computer_id` BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN finished_at IS NULL AND kind IN ('create','rebuild','pause','resume','delete') THEN cloud_computer_id ELSE NULL END) STORED,
    PRIMARY KEY (id),
    UNIQUE KEY uq_cloud_operation_token (operation_token),
    UNIQUE KEY uq_cloud_operation_receipt (command_receipt_id),
    UNIQUE KEY uq_cloud_operation_active (active_computer_id),
    KEY idx_cloud_operation_computer (cloud_computer_id,status,id),
    KEY idx_cloud_operation_due (status,updated_at,id),
    KEY idx_cloud_operation_public (public_operation_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
