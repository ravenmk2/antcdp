CREATE TABLE `agent_model_call` (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    session_id BIGINT UNSIGNED NOT NULL,
    run_id BIGINT UNSIGNED NULL,
    root_run_id BIGINT UNSIGNED NULL,
    compaction_id BIGINT UNSIGNED NULL,
    step_no INT UNSIGNED NOT NULL,
    attempt_no INT UNSIGNED NOT NULL,
    purpose VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    generation_slot TINYINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN purpose = 'generation' THEN 1 ELSE NULL END) STORED,
    status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    provider_id BIGINT UNSIGNED NOT NULL,
    model_definition_id BIGINT UNSIGNED NOT NULL,
    protocol VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    requested_model_id VARCHAR(255) COLLATE utf8mb4_0900_bin NOT NULL,
    response_model_id VARCHAR(255) COLLATE utf8mb4_0900_bin NULL,
    thinking JSON NOT NULL,
    request_config JSON NOT NULL,
    -- 固定投影版本、可见事件/替换引用与工具组顺序；重放不读取实时配置，不另存可变消息正文。
    surface_manifest JSON NOT NULL,
    request_hash BINARY(32) NOT NULL,
    capability_snapshot JSON NOT NULL,
    budget_reservation JSON NULL,
    budget_settlement JSON NULL,
    provider_request_id VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NULL,
    executor_epoch VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    fence_version BIGINT UNSIGNED NOT NULL,
    response_event_seq BIGINT UNSIGNED NULL,
    input_tokens BIGINT UNSIGNED NULL,
    output_tokens BIGINT UNSIGNED NULL,
    cache_read_tokens BIGINT UNSIGNED NULL,
    cache_write_tokens BIGINT UNSIGNED NULL,
    usage_raw JSON NULL,
    usage_semantics_version VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    usage_completeness VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    estimated_cost DECIMAL(20,8) NULL,
    cost_currency VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NULL,
    pricing_snapshot JSON NULL,
    error_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    created_at DATETIME(3) NOT NULL,
    started_at DATETIME(3) NULL,
    deadline_at DATETIME(3) NOT NULL,
    finished_at DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_agent_model_call_attempt (run_id, step_no, attempt_no, generation_slot),
    UNIQUE KEY uq_agent_model_compaction_attempt (compaction_id, attempt_no),
    KEY idx_agent_model_call_usage (provider_id, model_definition_id, created_at, id),
    KEY idx_agent_model_call_session (session_id, created_at, id),
    KEY idx_agent_model_call_root (root_run_id, id),
    KEY idx_agent_model_call_pending (status, deadline_at, id)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
