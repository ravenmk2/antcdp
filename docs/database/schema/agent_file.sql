CREATE TABLE `agent_file` (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    purpose VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    content_domain VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    content_session_id BIGINT UNSIGNED NULL,
    owner_user_id BIGINT UNSIGNED NULL,
    agent_id BIGINT UNSIGNED NULL,
    storage_key VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    writer_token VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    integrity_state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    size_bytes BIGINT UNSIGNED NULL,
    sha256 BINARY(32) NULL,
    media_type VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    media_properties JSON NULL,
    uploaded_by_user_id BIGINT UNSIGNED NULL,
    created_by_tool_call_id BIGINT UNSIGNED NULL,
    upload_operation_id BIGINT UNSIGNED NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    expires_at DATETIME(3) NULL,
    bound_at DATETIME(3) NULL,
    orphaned_at DATETIME(3) NULL,
    integrity_checked_at DATETIME(3) NULL,
    deleted_at DATETIME(3) NULL,
    error_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_agent_file_storage (storage_key),
    UNIQUE KEY uq_agent_file_writer (writer_token),
    KEY idx_agent_file_session (content_session_id, state, id),
    KEY idx_agent_file_expiry (state, expires_at, id),
    KEY idx_agent_file_orphan (state, orphaned_at, id),
    KEY idx_agent_file_upload_operation (upload_operation_id)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
