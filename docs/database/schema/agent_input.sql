CREATE TABLE `agent_input` (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    session_id BIGINT UNSIGNED NOT NULL,
    command_receipt_id BIGINT UNSIGNED NULL,
    input_kind VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    origin_kind VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    actor_kind VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    actor_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    source_kind VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
    source_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
    last_modified_by_kind VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    last_modified_by_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    queue_order BIGINT UNSIGNED NOT NULL,
    claimed_run_id BIGINT UNSIGNED NULL,
    claimed_step_no INT UNSIGNED NULL,
    question_interaction_id BIGINT UNSIGNED NULL,
    pending_question_slot BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN input_kind = 'question_reply' AND status = 'pending' THEN question_interaction_id ELSE NULL END) STORED,
    retry_of_run_id BIGINT UNSIGNED NULL,
    continuation_seq BIGINT UNSIGNED NULL,
    accepted_seq BIGINT UNSIGNED NOT NULL,
    current_content_seq BIGINT UNSIGNED NOT NULL,
    message_seq BIGINT UNSIGNED NULL,
    content_revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    row_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    queue_deadline_at DATETIME(3) NOT NULL,
    claimed_at DATETIME(3) NULL,
    ended_at DATETIME(3) NULL,
    end_reason VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_agent_input_receipt (command_receipt_id),
    UNIQUE KEY uq_agent_input_order (session_id, queue_order),
    UNIQUE KEY uq_agent_input_pending_answer (pending_question_slot),
    KEY idx_agent_input_queue (session_id, status, queue_order),
    KEY idx_agent_input_deadline (status, queue_deadline_at, id),
    KEY idx_agent_input_claimed (claimed_run_id, claimed_step_no, id),
    KEY idx_agent_input_interaction (question_interaction_id, id)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
