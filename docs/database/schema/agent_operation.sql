CREATE TABLE `agent_operation` (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    command_receipt_id BIGINT UNSIGNED NOT NULL,
    kind VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    subject_kind VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    subject_id BIGINT UNSIGNED NULL,
    content_domain VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    content_session_id BIGINT UNSIGNED NULL,
    owner_user_id BIGINT UNSIGNED NULL,
    agent_id BIGINT UNSIGNED NULL,
    status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    config_snapshot JSON NOT NULL,
    result JSON NULL,
    staged_file_id BIGINT UNSIGNED NULL,
    published_skill_version_id BIGINT UNSIGNED NULL,
    error_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    actor_user_id BIGINT UNSIGNED NOT NULL,
    executor_epoch VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    fence_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
    created_at DATETIME(3) NOT NULL,
    started_at DATETIME(3) NULL,
    deadline_at DATETIME(3) NOT NULL,
    finished_at DATETIME(3) NULL,
    expires_at DATETIME(3) NULL,
    updated_at DATETIME(3) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_agent_operation_receipt (command_receipt_id),
    KEY idx_agent_operation_subject (subject_kind, subject_id, created_at, id),
    KEY idx_agent_operation_due (status, deadline_at, id),
    KEY idx_agent_operation_expiry (published_skill_version_id, expires_at, id),
    KEY idx_agent_operation_content (content_domain, owner_user_id, created_at, id),
    KEY idx_agent_operation_session (content_session_id, id)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
