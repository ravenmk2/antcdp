CREATE TABLE `agent_run` (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    session_id BIGINT UNSIGNED NOT NULL,
    root_run_id BIGINT UNSIGNED NULL,
    parent_run_id BIGINT UNSIGNED NULL,
    trigger_input_id BIGINT UNSIGNED NULL,
    retry_of_run_id BIGINT UNSIGNED NULL,
    executor_user_id BIGINT UNSIGNED NOT NULL,
    origin_kind VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    actor_kind VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    actor_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    source_kind VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
    source_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
    status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    active_slot TINYINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN settled_at IS NULL THEN 1 ELSE NULL END) STORED,
    agent_config_version BIGINT UNSIGNED NOT NULL,
    resource_config_version BIGINT UNSIGNED NOT NULL,
    execution_policy_snapshot JSON NOT NULL,
    model_selection_hash BINARY(32) NOT NULL,
    budget_limit JSON NOT NULL,
    budget_reserved JSON NOT NULL,
    budget_used JSON NOT NULL,
    budget_revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    current_step_no INT UNSIGNED NOT NULL DEFAULT 0,
    executor_epoch VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    fence_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
    started_seq BIGINT UNSIGNED NULL,
    ended_seq BIGINT UNSIGNED NULL,
    continuation_seq BIGINT UNSIGNED NULL,
    end_reason VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    usage_completeness VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    created_at DATETIME(3) NOT NULL,
    started_at DATETIME(3) NULL,
    deadline_at DATETIME(3) NOT NULL,
    stop_requested_at DATETIME(3) NULL,
    stop_actor_kind VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    stop_actor_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
    stop_deadline_at DATETIME(3) NULL,
    finished_at DATETIME(3) NULL,
    settled_at DATETIME(3) NULL,
    updated_at DATETIME(3) NOT NULL,
    projection_seq BIGINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uq_agent_run_active (session_id, active_slot),
    UNIQUE KEY uq_agent_run_trigger (trigger_input_id),
    KEY idx_agent_run_family (root_run_id, parent_run_id, id),
    KEY idx_agent_run_session (session_id, created_at, id),
    KEY idx_agent_run_result (session_id, root_run_id, ended_seq),
    KEY idx_agent_run_deadline (status, deadline_at, id),
    KEY idx_agent_run_executor (executor_epoch, status, id),
    KEY idx_agent_run_settlement (root_run_id, settled_at, finished_at, updated_at, id)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
